/**
 * Orderly duplicate-identity remediation (Task #1121)
 *
 * Repairs inventory items that were accidentally created as separate identities
 * by the confirmed Orderly XLSX Item Code defect (fixed for new imports by
 * Task #1108). This service is deliberately NOT a general deduplicator:
 *
 *   - Candidates come only from reliable Orderly Item Code provenance:
 *     approved import rows whose `itemCodeStatus = 'valid'` resolved to more
 *     than one inventory item within one (company, source system, source
 *     property) scope, plus the authoritative external mapping for that code.
 *   - Item names are never a grouping key. Two items with identical names but
 *     no shared reliable source code are invisible to this service.
 *   - REPORT mode performs no writes at all.
 *   - APPLY mode mutates only groups named in a manifest bound to a report
 *     hash, and only groups classified SAFE_CANDIDATE.
 *
 * Repair semantics: historical evidence is repointed, never rewritten. Count
 * rows keep their quantities, unit costs, dates, storage locations, source
 * rows, and batch identity — only the `inventory_item_id` FK moves. Duplicate
 * catalog items are superseded (deactivated + linked to the canonical item),
 * never deleted.
 *
 * See `orderlyDuplicateRemediation.db.test.ts` for the behavioural contract.
 */

