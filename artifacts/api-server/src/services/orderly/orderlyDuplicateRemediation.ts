/**
 * Confirms the store belongs to the company and the source property is bound
 * to that exact store. This is the same authorization boundary the import
 * approval path enforces, re-checked here because remediation mutates the same
 * identity rows.
 */
export async function resolveScope(
  input: { companyId: string; storeId: string; sourceSystem: string; sourcePropertyId?: string },
  runner: typeof db = db,
): Promise<RemediationScope> {
  const [store] = await runner
    .select({ id: companyStores.id, companyId: companyStores.companyId })
    .from(companyStores)
    .where(and(eq(companyStores.id, input.storeId), eq(companyStores.companyId, input.companyId)));
  if (!store) {
    throw new RemediationScopeError(
      `Store ${input.storeId} does not belong to company ${input.companyId}.`,
    );
  }

  const bindings = await runner
    .select({
      sourcePropertyId: importSourcePropertyBindings.sourcePropertyId,
      destinationStoreId: importSourcePropertyBindings.destinationStoreId,
      active: importSourcePropertyBindings.active,
    })
    .from(importSourcePropertyBindings)
    .where(
      and(
        eq(importSourcePropertyBindings.companyId, input.companyId),
        eq(importSourcePropertyBindings.sourceSystem, input.sourceSystem),
        eq(importSourcePropertyBindings.destinationStoreId, input.storeId),
        eq(importSourcePropertyBindings.active, 1),
      ),
    );

  if (input.sourcePropertyId != null && input.sourcePropertyId !== '') {
    const match = bindings.find(
      (binding: { sourcePropertyId: string }) => binding.sourcePropertyId === input.sourcePropertyId,
    );
    if (!match) {
      throw new RemediationScopeError(
        `Source property ${input.sourcePropertyId} is not bound to store ${input.storeId} ` +
          `for ${input.sourceSystem} in company ${input.companyId}.`,
      );
    }
    return {
      companyId: input.companyId,
      storeId: input.storeId,
      sourceSystem: input.sourceSystem,
      sourcePropertyId: input.sourcePropertyId,
    };
  }

  if (bindings.length > 1) {
    throw new RemediationScopeError(
      `Store ${input.storeId} has ${bindings.length} approved ${input.sourceSystem} source ` +
        'properties. Pass --source-property to name exactly one.',
    );
  }

  return {
    companyId: input.companyId,
    storeId: input.storeId,
    sourceSystem: input.sourceSystem,
    // No binding yet — legacy pre-binding mappings/batches use ''.
    sourcePropertyId: bindings[0]?.sourcePropertyId ?? '',
  };
}


/**
 * Reads the configuration values a merge could silently discard, as a sorted,
 * stable list of strings suitable for hashing.
 *
 * These are exactly the fields the unique constraints do NOT cover:
 *   - inventory_item_units: unique(item, unit, isIssueUnit) omits the
 *     conversion factor that recipe and transfer costing divide by.
 *   - inventory_item_location_assignments: unique(item, location) omits the
 *     par target, primary designation, and active flag.
 *   - store_inventory_items: unique(store, item) omits the primary location,
 *     par level, reorder level, and active flag. onHandQty is excluded because
 *     the repair re-derives it from the repointed count history (see
 *     `recomputeStoreOnHand`), so a difference there is expected, not a conflict.
 *   - inventory_item_locations (deprecated): the primary designation.
 *
 * Hashing the values (not just the row counts) is what makes the group hash
 * able to detect a post-review edit to one of them.
 */
async function mergeSensitiveConfigOf(runner: typeof db, itemId: string): Promise<string[]> {
  const [unitRows, assignmentRows, storeRows, legacyRows] = await Promise.all([
    runner
      .select({
        unitId: inventoryItemUnits.unitId,
        isIssueUnit: inventoryItemUnits.isIssueUnit,
        unitsPerCanonical: inventoryItemUnits.unitsPerCanonical,
      })
      .from(inventoryItemUnits)
      .where(eq(inventoryItemUnits.inventoryItemId, itemId)) as Promise<
      Array<{ unitId: string; isIssueUnit: number; unitsPerCanonical: number }>
    >,
    runner
      .select({
        locationId: inventoryItemLocationAssignments.locationId,
        parTarget: inventoryItemLocationAssignments.parTarget,
        isPrimary: inventoryItemLocationAssignments.isPrimary,
        active: inventoryItemLocationAssignments.active,
      })
      .from(inventoryItemLocationAssignments)
      .where(eq(inventoryItemLocationAssignments.inventoryItemId, itemId)) as Promise<
      Array<{ locationId: string; parTarget: number | null; isPrimary: number; active: number }>
    >,
    runner
      .select({
        storeId: storeInventoryItems.storeId,
        primaryLocationId: storeInventoryItems.primaryLocationId,
        parLevel: storeInventoryItems.parLevel,
        reorderLevel: storeInventoryItems.reorderLevel,
        active: storeInventoryItems.active,
      })
      .from(storeInventoryItems)
      .where(eq(storeInventoryItems.inventoryItemId, itemId)) as Promise<
      Array<{
        storeId: string;
        primaryLocationId: string | null;
        parLevel: number | null;
        reorderLevel: number | null;
        active: number;
      }>
    >,
    runner
      .select({
        storageLocationId: inventoryItemLocations.storageLocationId,
        isPrimary: inventoryItemLocations.isPrimary,
      })
      .from(inventoryItemLocations)
      .where(eq(inventoryItemLocations.inventoryItemId, itemId)) as Promise<
      Array<{ storageLocationId: string; isPrimary: number }>
    >,
  ]);

  return [
    ...unitRows.map(
      row => `unit:${row.unitId}:issue=${row.isIssueUnit}:per=${row.unitsPerCanonical}`,
    ),
    ...assignmentRows.map(
      row =>
        `assign:${row.locationId}:par=${fmt(row.parTarget)}` +
        `:primary=${row.isPrimary}:active=${row.active}`,
    ),
    ...storeRows.map(
      row =>
        `store:${row.storeId}:primaryLoc=${row.primaryLocationId ?? 'unset'}` +
        `:par=${fmt(row.parLevel)}:reorder=${fmt(row.reorderLevel)}:active=${row.active}`,
    ),
    ...legacyRows.map(row => `legacyLoc:${row.storageLocationId}:primary=${row.isPrimary}`),
  ].sort();
}

