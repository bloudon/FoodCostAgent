async function countEvidence(
  runner: typeof db,
  companyId: string,
  itemId: string,
): Promise<{
  locations: number;
  sessions: number;
  valuation: number;
  sessionIds: string[];
  /**
   * Per-line fingerprint: line identity plus the values the repair carries and
   * the valuation is derived from.
   *
   * Counting lines is not enough to bind them. Editing a qty or unit cost in
   * place leaves the line count, the location count, and the session count all
   * unchanged, so a hash built from counts alone still validates and the apply
   * proceeds against numbers the reviewer never saw — and records a stale
   * `valuationBefore` in the audit while doing it.
   */
  lineFingerprint: string[];
}> {
  const rows = await runner
    .select({
      id: inventoryCountLines.id,
      storageLocationId: inventoryCountLines.storageLocationId,
      inventoryCountId: inventoryCountLines.inventoryCountId,
      qty: inventoryCountLines.qty,
      unitCost: inventoryCountLines.unitCost,
    })
    .from(inventoryCountLines)
    .innerJoin(inventoryCounts, eq(inventoryCounts.id, inventoryCountLines.inventoryCountId))
    .where(
      and(eq(inventoryCountLines.inventoryItemId, itemId), eq(inventoryCounts.companyId, companyId)),
    );

  const locations = new Set<string>();
  const sessions = new Set<string>();
  const lineFingerprint: string[] = [];
  let valuation = 0;
  for (const row of rows as Array<{
    id: string;
    storageLocationId: string;
    inventoryCountId: string;
    qty: number;
    unitCost: number;
  }>) {
    locations.add(row.storageLocationId);
    sessions.add(row.inventoryCountId);
    valuation += (row.qty ?? 0) * (row.unitCost ?? 0);
    lineFingerprint.push(
      `line:${row.id}:session=${row.inventoryCountId}:loc=${row.storageLocationId}` +
        `:qty=${fmt(row.qty)}:cost=${fmt(row.unitCost)}`,
    );
  }
  return {
    locations: locations.size,
    sessions: sessions.size,
    valuation: round2(valuation),
    sessionIds: [...sessions].sort(),
    lineFingerprint: lineFingerprint.sort(),
  };
}

// ─── Canonical selection ──────────────────────────────────────────────────────

/**
 * Deterministic, evidence-led ranking. Higher wins. Never falls back to UUID
 * order, query order, or display name: when the evidence ties, the group is
 * reported AMBIGUOUS instead.
 *
 * Weights are ordered so a stronger signal cannot be outvoted by weaker ones:
 *   1. authoritative external mapping for the source code
 *   2. earliest valid import-created identity
 *   3. downstream reference volume
 *   4. store/location linkage
 *   5. existing historical use (count sessions)
 *   6. metadata completeness
 */
interface RankInput {
  hasAuthoritativeMapping: boolean;
  isEarliestImport: boolean;
  totalReferences: number;
  hasStoreLinkage: boolean;
  countSessionCount: number;
  metadataCompleteness: number;
}

function rankComponents(input: RankInput): Array<{ label: string; value: number }> {
  return [
    { label: 'authoritative external mapping', value: input.hasAuthoritativeMapping ? 1 : 0 },
    { label: 'earliest valid import-created identity', value: input.isEarliestImport ? 1 : 0 },
    { label: 'downstream references', value: input.totalReferences },
    { label: 'store/location linkage', value: input.hasStoreLinkage ? 1 : 0 },
    { label: 'existing historical use', value: input.countSessionCount },
    { label: 'metadata completeness', value: input.metadataCompleteness },
  ];
}

/** Lexicographic comparison over the ranked signal vector. */
function compareRank(a: CandidateItem, b: CandidateItem, earliest: Set<string>): number {
  const left = rankComponents({
    hasAuthoritativeMapping: a.hasAuthoritativeMapping,
    isEarliestImport: earliest.has(a.itemId),
    totalReferences: a.totalReferences,
    hasStoreLinkage: a.referenceCounts.storeInventoryItems > 0,
    countSessionCount: a.countSessionCount,
    metadataCompleteness: a.metadataCompleteness,
  });
  const right = rankComponents({
    hasAuthoritativeMapping: b.hasAuthoritativeMapping,
    isEarliestImport: earliest.has(b.itemId),
    totalReferences: b.totalReferences,
    hasStoreLinkage: b.referenceCounts.storeInventoryItems > 0,
    countSessionCount: b.countSessionCount,
    metadataCompleteness: b.metadataCompleteness,
  });
  for (let i = 0; i < left.length; i++) {
    if (left[i].value !== right[i].value) return right[i].value - left[i].value;
  }
  return 0;
}

function describeSelection(
  winner: CandidateItem,
  runnerUp: CandidateItem | undefined,
  earliest: Set<string>,
): string {
  const signals = rankComponents({
    hasAuthoritativeMapping: winner.hasAuthoritativeMapping,
    isEarliestImport: earliest.has(winner.itemId),
    totalReferences: winner.totalReferences,
    hasStoreLinkage: winner.referenceCounts.storeInventoryItems > 0,
    countSessionCount: winner.countSessionCount,
    metadataCompleteness: winner.metadataCompleteness,
  });
  if (!runnerUp) {
    return `only surviving candidate (${signals
      .filter(signal => signal.value > 0)
      .map(signal => signal.label)
      .join(', ') || 'no distinguishing evidence'})`;
  }
  const runnerSignals = rankComponents({
    hasAuthoritativeMapping: runnerUp.hasAuthoritativeMapping,
    isEarliestImport: earliest.has(runnerUp.itemId),
    totalReferences: runnerUp.totalReferences,
    hasStoreLinkage: runnerUp.referenceCounts.storeInventoryItems > 0,
    countSessionCount: runnerUp.countSessionCount,
    metadataCompleteness: runnerUp.metadataCompleteness,
  });
  for (let i = 0; i < signals.length; i++) {
    if (signals[i].value !== runnerSignals[i].value) {
      return `decided on ${signals[i].label} (${signals[i].value} vs ${runnerSignals[i].value})`;
    }
  }
  return 'no decisive evidence';
}

function metadataCompletenessOf(item: {
  categoryId: string | null;
  containerSize: number | null;
  casePkgCount: number | null;
  barcode: string | null;
  pluSku: string | null;
  pricePerUnit: number;
}): number {
  let filled = 0;
  if (item.categoryId) filled++;
  if (item.containerSize != null) filled++;
  if (item.casePkgCount != null) filled++;
  if (item.barcode) filled++;
  if (item.pluSku) filled++;
  if (item.pricePerUnit > 0) filled++;
  return filled;
}

// ─── Report mode (read-only) ──────────────────────────────────────────────────

/**
 * Builds the read-only remediation report. Performs no writes.
 *
 * Discovery evidence, in order:
 *   1. approved import batches in scope (company + source system + source
 *      property + destination store),
 *   2. their rows with a reliable Item Code (`itemCodeStatus = 'valid'`) and a
 *      `resolvedInventoryItemId`,
 *   3. codes whose rows resolved to 2+ distinct inventory items, plus any item
 *      the authoritative external mapping for that code points at.
 */
export async function buildRemediationReport(
  scope: RemediationScope,
  runner: typeof db = db,
  options: {
    /**
     * Restrict discovery to these source codes only. Used by the per-group
     * under-lock freshness recheck in APPLY: a group's facts (candidates,
     * classification, conflicts, evidence, per-group hash) are derived
     * exclusively from that code's rows, mappings, prior audits, and candidate
     * items, so filtering to one code yields byte-identical group output while
     * skipping the other groups' ~23 queries per candidate. The returned
     * report-level hash and totals then describe only the filtered population
     * and MUST NOT be compared against whole-report hashes.
     */
    onlySourceCodes?: string[];
  } = {},
): Promise<RemediationReport> {
  // Batch scoping is resolved by the shared helper so that discovery, the
  // apply-time exclusivity check, and reconciliation cannot disagree about
  // which batches are in scope. A group discovered from a legacy batch that
  // apply then judged out of scope would be found and never repairable.
  const { batches } = await resolveScopedBatches(scope, runner);

  const batchIds = batches.map(batch => batch.id);
  const groups: RemediationGroup[] = [];

  if (batchIds.length > 0) {
    const rows = (await runner
      .select({
        batchId: inventoryImportRows.batchId,
        rowIndex: inventoryImportRows.rowIndex,
        sourceItemCode: inventoryImportRows.sourceItemCode,
        cleanedDescription: inventoryImportRows.cleanedDescription,
        rawDescription: inventoryImportRows.rawDescription,
        caseQuantity: inventoryImportRows.caseQuantity,
        baseUnit: inventoryImportRows.baseUnit,
        storageLocation: inventoryImportRows.storageLocation,
        resolvedInventoryItemId: inventoryImportRows.resolvedInventoryItemId,
      })
      .from(inventoryImportRows)
      .where(
        and(
          inArray(inventoryImportRows.batchId, batchIds),
          eq(inventoryImportRows.itemCodeStatus, 'valid'),
          isNotNull(inventoryImportRows.resolvedInventoryItemId),
        ),
      )) as Array<{
      batchId: string;
      rowIndex: number;
      sourceItemCode: string | null;
      cleanedDescription: string | null;
      rawDescription: string | null;
      caseQuantity: number | null;
      baseUnit: string | null;
      storageLocation: string | null;
      resolvedInventoryItemId: string;
    }>;

    // Group source rows by reliable code.
    const requestedCodes = options.onlySourceCodes ? new Set(options.onlySourceCodes) : null;
    const byCode = new Map<string, typeof rows>();
    for (const row of rows) {
      const code = row.sourceItemCode?.trim();
      if (!code) continue;
      if (requestedCodes && !requestedCodes.has(code)) continue;
      const bucket = byCode.get(code) ?? [];
      bucket.push(row);
      byCode.set(code, bucket);
    }

    // Authoritative mappings for the codes in play, scoped exactly.
    const codes = [...byCode.keys()];
    const mappings =
      codes.length === 0
        ? []
        : ((await runner
            .select({
              sourceExternalId: inventoryItemExternalMappings.sourceExternalId,
              inventoryItemId: inventoryItemExternalMappings.inventoryItemId,
            })
            .from(inventoryItemExternalMappings)
            .where(
              and(
                eq(inventoryItemExternalMappings.companyId, scope.companyId),
                eq(inventoryItemExternalMappings.sourceSystem, scope.sourceSystem),
                eq(inventoryItemExternalMappings.sourcePropertyId, scope.sourcePropertyId),
                inArray(inventoryItemExternalMappings.sourceExternalId, codes),
              ),
            )) as Array<{ sourceExternalId: string; inventoryItemId: string }>);
    const mappedByCode = new Map<string, string[]>();
    for (const mapping of mappings) {
      const list = mappedByCode.get(mapping.sourceExternalId) ?? [];
      list.push(mapping.inventoryItemId);
      mappedByCode.set(mapping.sourceExternalId, list);
    }

    const batchOrder = new Map<string, number>();
    for (const batch of batches as Array<{
      id: string;
      inventoryDate: string | null;
      approvedAt: Date | null;
      uploadedAt: Date;
    }>) {
      // Provenance order: inventory date first (the business period), then the
      // approval/upload instant. Both come from the source workbook lifecycle,
      // never from row ordering.
      const dateKey = batch.inventoryDate ? Date.parse(`${batch.inventoryDate}T00:00:00Z`) : Number.MAX_SAFE_INTEGER;
      const approvalKey = (batch.approvedAt ?? batch.uploadedAt)?.getTime?.() ?? Number.MAX_SAFE_INTEGER;
      batchOrder.set(batch.id, dateKey * 1e4 + (approvalKey % 1e4));
    }
    const batchDates = new Map(
      (batches as Array<{ id: string; inventoryDate: string | null }>).map(batch => [
        batch.id,
        batch.inventoryDate,
      ]),
    );

    // Items already superseded by a previous applied run. Once a group is
    // repaired its duplicates carry no mapping and no import provenance, so
    // without this the group would vanish from discovery and a rerun of the
    // same manifest would look like drift instead of a no-op.
    const priorAudits =
      codes.length === 0
        ? []
        : ((await runner
            .select({
              sourceExternalId: inventoryItemRemediationAudit.sourceExternalId,
              supersededItemIds: inventoryItemRemediationAudit.supersededItemIds,
            })
            .from(inventoryItemRemediationAudit)
            .where(
              and(
                eq(inventoryItemRemediationAudit.companyId, scope.companyId),
                eq(inventoryItemRemediationAudit.sourceSystem, scope.sourceSystem),
                eq(inventoryItemRemediationAudit.sourcePropertyId, scope.sourcePropertyId),
                eq(inventoryItemRemediationAudit.result, 'applied'),
                inArray(inventoryItemRemediationAudit.sourceExternalId, codes),
              ),
            )) as Array<{ sourceExternalId: string; supersededItemIds: string[] }>);
    const supersededByCode = new Map<string, string[]>();
    for (const audit of priorAudits) {
      const list = supersededByCode.get(audit.sourceExternalId) ?? [];
      list.push(...(audit.supersededItemIds ?? []));
      supersededByCode.set(audit.sourceExternalId, list);
    }

    for (const code of codes.sort()) {
      const codeRows = byCode.get(code)!;
      const resolvedIds = new Set(codeRows.map(row => row.resolvedInventoryItemId));
      const mappedIds = mappedByCode.get(code) ?? [];
      const previouslySuperseded = supersededByCode.get(code) ?? [];
      const candidateIds = new Set<string>([...resolvedIds, ...mappedIds, ...previouslySuperseded]);

      if (candidateIds.size < 2) continue; // single identity — nothing to repair

      // Earliest provenance per candidate item.
      const earliestByItem = new Map<string, number>();
      for (const row of codeRows) {
        const order = batchOrder.get(row.batchId) ?? Number.MAX_SAFE_INTEGER;
        const current = earliestByItem.get(row.resolvedInventoryItemId);
        if (current == null || order < current) {
          earliestByItem.set(row.resolvedInventoryItemId, order);
        }
      }
      const minOrder = Math.min(...earliestByItem.values());
      const earliestItems = new Set(
        [...earliestByItem.entries()].filter(([, order]) => order === minOrder).map(([id]) => id),
      );

      const itemRows = (await runner
        .select({
          id: inventoryItems.id,
          companyId: inventoryItems.companyId,
          name: inventoryItems.name,
          active: inventoryItems.active,
          supersededByItemId: inventoryItems.supersededByItemId,
          categoryId: inventoryItems.categoryId,
          unitId: inventoryItems.unitId,
          caseSize: inventoryItems.caseSize,
          containerSize: inventoryItems.containerSize,
          casePkgCount: inventoryItems.casePkgCount,
          barcode: inventoryItems.barcode,
          pluSku: inventoryItems.pluSku,
          pricePerUnit: inventoryItems.pricePerUnit,
        })
        .from(inventoryItems)
        .where(
          and(
            inArray(inventoryItems.id, [...candidateIds]),
            eq(inventoryItems.companyId, scope.companyId),
          ),
        )) as Array<{
        id: string;
        companyId: string;
        name: string;
        active: number;
        supersededByItemId: string | null;
        categoryId: string | null;
        unitId: string;
        caseSize: number;
        containerSize: number | null;
        casePkgCount: number | null;
        barcode: string | null;
        pluSku: string | null;
        pricePerUnit: number;
      }>;

      const conflictReasons: string[] = [];
      const ambiguityReasons: string[] = [];

      // Cross-tenant safety: every candidate must belong to the scoped company.
      if (itemRows.length !== candidateIds.size) {
        conflictReasons.push(
          'one or more candidate items are missing or belong to another company',
        );
      }

      const candidates: CandidateItem[] = [];
      for (const item of itemRows) {
        const [referenceCounts, evidence, mergeSensitiveConfig] = await Promise.all([
          countReferences(runner, scope.companyId, item.id),
          countEvidence(runner, scope.companyId, item.id),
          mergeSensitiveConfigOf(runner, item.id),
        ]);
        candidates.push({
          itemId: item.id,
          name: item.name,
          active: item.active,
          supersededByItemId: item.supersededByItemId,
          categoryId: item.categoryId,
          unitId: item.unitId,
          caseSize: item.caseSize,
          containerSize: item.containerSize,
          casePkgCount: item.casePkgCount,
          barcode: item.barcode,
          pluSku: item.pluSku,
          pricePerUnit: item.pricePerUnit,
          hasAuthoritativeMapping: mappedIds.includes(item.id),
          earliestImportResolvedAt: null,
          totalReferences: sumReferences(referenceCounts),
          referenceCounts,
          countLocationCount: evidence.locations,
          countSessionCount: evidence.sessions,
          valuationContribution: evidence.valuation,
          mergeSensitiveConfig,
          countLineFingerprint: evidence.lineFingerprint,
          metadataCompleteness: metadataCompletenessOf(item),
          rankScore: 0,
        });
      }
      candidates.sort((a, b) => a.itemId.localeCompare(b.itemId));

      // ── Compatibility: the same narrow rules the importer uses ─────────────
      const descriptions = new Set(
        codeRows
          .map(row => normalizeText(row.cleanedDescription ?? row.rawDescription))
          .filter(Boolean),
      );
      const caseQuantities = new Set(
        codeRows.map(row => row.caseQuantity).filter((q): q is number => q != null && q > 0),
      );
      const baseUnits = new Set(codeRows.map(row => normalizeText(row.baseUnit)).filter(Boolean));
      const storageLocations = new Set(
        codeRows.map(row => normalizeText(row.storageLocation)).filter(Boolean),
      );

      if (descriptions.size > 1) {
        const tokenSets = [...descriptions].map(
          description => new Set(description.split(' ').filter(Boolean)),
        );
        for (let left = 0; left < tokenSets.length; left++) {
          for (let right = left + 1; right < tokenSets.length; right++) {
            const overlap = [...tokenSets[left]].filter(token => tokenSets[right].has(token)).length;
            const union = new Set([...tokenSets[left], ...tokenSets[right]]).size;
            if (union > 0 && overlap / union < 0.5) {
              conflictReasons.push('materially different normalized product descriptions');
            }
          }
        }
      }
      if (caseQuantities.size > 1) conflictReasons.push('incompatible case quantities');
      if (baseUnits.size > 1) conflictReasons.push('incompatible base units');
      if (mappedIds.length > 1) {
        conflictReasons.push('more than one authoritative external mapping for this source code');
      }
      if (new Set(candidates.map(candidate => candidate.unitId)).size > 1) {
        conflictReasons.push('candidate items use different canonical inventory units');
      }
      const immutableEvidence = candidates.reduce(
        (total, candidate) => total + candidate.referenceCounts.historicalInvoiceLines,
        0,
      );
      if (immutableEvidence > 0) {
        conflictReasons.push(
          `${immutableEvidence} immutable historical invoice line(s) reference these items and cannot be repointed`,
        );
      }

      // ── Classification + canonical selection ──────────────────────────────
      const uniqueConflicts = [...new Set(conflictReasons)];
      let classification: GroupClassification;
      let proposedCanonicalItemId: string | null = null;
      let canonicalSelectionReason: string | null = null;

      const alreadySuperseded = candidates.filter(
        candidate => candidate.supersededByItemId != null,
      );
      const survivors = candidates.filter(candidate => candidate.supersededByItemId == null);

      if (uniqueConflicts.length > 0) {
        classification = 'CONFLICT';
      } else if (survivors.length < 2) {
        // Every duplicate is already superseded onto one canonical identity.
        classification = 'NOT_DEFECT_RELATED';
        proposedCanonicalItemId = survivors[0]?.itemId ?? null;
        canonicalSelectionReason =
          alreadySuperseded.length > 0 ? 'group already remediated' : 'single surviving identity';
      } else {
        const ranked = [...survivors].sort((a, b) => compareRank(a, b, earliestItems));
        const [winner, runnerUp] = ranked;
        if (compareRank(winner, runnerUp, earliestItems) === 0) {
          ambiguityReasons.push(
            `candidates ${winner.itemId} and ${runnerUp.itemId} are equally supported by every ranking signal`,
          );
          classification = 'AMBIGUOUS';
        } else {
          classification = 'SAFE_CANDIDATE';
          proposedCanonicalItemId = winner.itemId;
          canonicalSelectionReason = describeSelection(winner, runnerUp, earliestItems);
        }
        for (const candidate of ranked) {
          candidate.rankScore = ranked.length - ranked.indexOf(candidate);
        }
      }

      for (const candidate of candidates) {
        if (earliestItems.has(candidate.itemId)) {
          const batchId = codeRows.find(
            row => row.resolvedInventoryItemId === candidate.itemId,
          )?.batchId;
          candidate.earliestImportResolvedAt = batchId ? (batchDates.get(batchId) ?? null) : null;
        }
      }

      const alternativeCandidateIds = candidates
        .map(candidate => candidate.itemId)
        .filter(id => id !== proposedCanonicalItemId)
        .sort();

      const referencesToRepoint = candidates
        .filter(candidate => candidate.itemId !== proposedCanonicalItemId)
        .reduce(
          (total, candidate) => addReferences(total, candidate.referenceCounts),
          { ...EMPTY_REFERENCE_COUNTS },
        );

      groups.push({
        sourceExternalId: code,
        classification,
        candidateItemIds: candidates.map(candidate => candidate.itemId),
        proposedCanonicalItemId,
        canonicalSelectionReason,
        alternativeCandidateIds,
        candidates,
        evidence: {
          importBatchIds: [...new Set(codeRows.map(row => row.batchId))].sort(),
          importInventoryDates: [
            ...new Set(
              codeRows
                .map(row => batchDates.get(row.batchId))
                .filter((date): date is string => Boolean(date)),
            ),
          ].sort(),
          sourceDescriptions: [...descriptions].sort(),
          sourceCaseQuantities: [...caseQuantities].sort((a, b) => a - b),
          sourceBaseUnits: [...baseUnits].sort(),
          sourceStorageLocations: [...storageLocations].sort(),
          mappedItemIds: [...mappedIds].sort(),
          conflictReasons: uniqueConflicts,
          ambiguityReasons,
        },
        referencesToRepoint,
        valuationContribution: round2(
          candidates.reduce((total, candidate) => total + candidate.valuationContribution, 0),
        ),
        affectedCountLocations: candidates.reduce(
          (total, candidate) => total + candidate.countLocationCount,
          0,
        ),
        affectedCountSessions: candidates.reduce(
          (total, candidate) => total + candidate.countSessionCount,
          0,
        ),
      });
    }
  }

  const totals = {
    groupsExamined: groups.length,
    safeCandidates: groups.filter(group => group.classification === 'SAFE_CANDIDATE').length,
    ambiguous: groups.filter(group => group.classification === 'AMBIGUOUS').length,
    conflicts: groups.filter(group => group.classification === 'CONFLICT').length,
    notDefectRelated: groups.filter(group => group.classification === 'NOT_DEFECT_RELATED').length,
    itemsThatWouldBeSuperseded: groups
      .filter(group => group.classification === 'SAFE_CANDIDATE')
      .reduce((total, group) => total + group.alternativeCandidateIds.length, 0),
    countLinesThatWouldRepoint: groups
      .filter(group => group.classification === 'SAFE_CANDIDATE')
      .reduce((total, group) => total + group.referencesToRepoint.inventoryCountLines, 0),
  };

  return {
    reportVersion: REMEDIATION_REPORT_VERSION,
    reportHash: computeReportHash(scope, groups),
    scope,
    generatedAt: new Date().toISOString(),
    totals,
    groups,
  };
}

/**
 * Hash over the material facts only: scope, and per group the code,
 * classification, canonical proposal, candidate set, and the reference counts
 * that would move. Deliberately excludes timestamps and display text so a
 * cosmetic change does not invalidate an approved manifest, while any change to
 * what would actually be mutated does.
 */
export function computeReportHash(scope: RemediationScope, groups: RemediationGroup[]): string {
  const material = {
    version: REMEDIATION_REPORT_VERSION,
    scope: {
      companyId: scope.companyId,
      storeId: scope.storeId,
      sourceSystem: scope.sourceSystem,
      sourcePropertyId: scope.sourcePropertyId,
    },
    groups: [...groups]
      .sort((a, b) => a.sourceExternalId.localeCompare(b.sourceExternalId))
      .map(group => ({
        code: group.sourceExternalId,
        classification: group.classification,
        canonical: group.proposedCanonicalItemId,
        candidates: [...group.candidateItemIds].sort(),
        references: group.referencesToRepoint,
        // Counts say how many rows exist; they cannot see a row being edited in
        // place. Everything below binds the VALUES the reviewer saw and the
        // repair will act on, so a post-review edit invalidates the approval.
        config: [...group.candidates]
          .sort((a, b) => a.itemId.localeCompare(b.itemId))
          .map(candidate => ({
            item: candidate.itemId,
            cfg: candidate.mergeSensitiveConfig,
            // Count-line identity + qty/cost: what the repair repoints and what
            // the valuation (and the audit's valuationBefore) is derived from.
            lines: candidate.countLineFingerprint,
            valuation: fmt(candidate.valuationContribution),
            // Item facts the report presents as the basis for the merge; an
            // edit to any of them changes what the reviewer approved.
            item_facts:
              `name=${candidate.name}:active=${candidate.active}` +
              `:superseded=${candidate.supersededByItemId ?? 'none'}` +
              `:category=${candidate.categoryId ?? 'none'}:unit=${candidate.unitId}` +
              `:case=${fmt(candidate.caseSize)}:container=${fmt(candidate.containerSize)}` +
              `:pkg=${fmt(candidate.casePkgCount)}:barcode=${candidate.barcode ?? 'none'}` +
              `:plu=${candidate.pluSku ?? 'none'}:price=${fmt(candidate.pricePerUnit)}` +
              `:mapped=${candidate.hasAuthoritativeMapping}`,
          })),
        // Group valuation, plus the source facts that decided COMPATIBILITY.
        // A description, case quantity, or base unit edited after review can
        // leave the candidate set and classification identical while changing
        // the evidence the merge was justified by.
        valuation: fmt(group.valuationContribution),
        importEvidence: {
          batches: [...group.evidence.importBatchIds].sort(),
          dates: [...group.evidence.importInventoryDates].sort(),
          descriptions: [...group.evidence.sourceDescriptions].sort(),
          caseQuantities: [...group.evidence.sourceCaseQuantities].sort((a, b) => a - b).map(fmt),
          baseUnits: [...group.evidence.sourceBaseUnits].sort(),
          storageLocations: [...group.evidence.sourceStorageLocations].sort(),
          mapped: [...group.evidence.mappedItemIds].sort(),
        },
        conflicts: [...group.evidence.conflictReasons].sort(),
        ambiguity: [...group.evidence.ambiguityReasons].sort(),
      })),
  };
  return createHash('sha256').update(JSON.stringify(material)).digest('hex');
}

/**
 * Hashes the part of the report the manifest does NOT approve.
 *
 * Applying an approved group necessarily changes the full-report hash, so the
 * full hash cannot be used as the apply-time authorization check without
 * breaking reruns. The unapproved remainder, by contrast, is untouched by
 * remediating approved groups — so if it moves, something genuinely changed in
 * this scope (a new duplicate group appeared, or a group the reviewer chose not
 * to approve now looks different) and the approval is no longer trustworthy.
 */
export function computeUnapprovedRemainderHash(
  report: RemediationReport,
  approvals: ReadonlyArray<Pick<ManifestGroupApproval, 'sourceExternalId'>>,
): string {
  const approvedCodes = new Set(approvals.map(approval => approval.sourceExternalId));
  const remainder = report.groups.filter(group => !approvedCodes.has(group.sourceExternalId));
  return computeReportHash(report.scope, remainder);
}

/**
 * Builds a manifest from a report, containing ONLY the safe groups the
 * reviewer explicitly named. There is deliberately no "approve all" helper: the
 * caller must pass the exact codes it reviewed.
 */
export function buildApplyManifest(
  report: RemediationReport,
  approvedSourceExternalIds: string[],
  manifestId: string,
): ApplyManifest {
  const approved = new Set(approvedSourceExternalIds);
  const groups: ManifestGroupApproval[] = [];
  for (const group of report.groups) {
    if (!approved.has(group.sourceExternalId)) continue;
    if (group.classification !== 'SAFE_CANDIDATE' || !group.proposedCanonicalItemId) {
      throw new Error(
        `Group ${group.sourceExternalId} is ${group.classification} and cannot be added to an apply manifest.`,
      );
    }
    groups.push({
      sourceExternalId: group.sourceExternalId,
      canonicalItemId: group.proposedCanonicalItemId,
      supersededItemIds: group.alternativeCandidateIds,
      groupHash: computeReportHash(report.scope, [group]),
    });
    approved.delete(group.sourceExternalId);
  }
  if (approved.size > 0) {
    throw new Error(`Approved codes not present in the report: ${[...approved].sort().join(', ')}`);
  }
  return {
    manifestId,
    reportVersion: report.reportVersion,
    reportHash: report.reportHash,
    unapprovedReportHash: computeUnapprovedRemainderHash(report, groups),
    scope: report.scope,
    groups,
  };
}

// ─── Apply mode ───────────────────────────────────────────────────────────────

/**
 * Applies a reviewed manifest. Per group:
 *   - re-derives the current report facts and rejects material drift,
 *   - repoints supported references inside one transaction,
 *   - supersedes (never deletes) the duplicate items,
 *   - writes one audit row.
 *
 * A group that hits a uniqueness collision, unexpected reference, or immutable
 * evidence stops with no partial mutation; other groups still run.
 */
export async function applyRemediationManifest(
  manifest: ApplyManifest,
  operatorId: string,
  runner: typeof db = db,
  options: {
    legacyAdoptionAuthorization?: LegacyAdoptionAuthorization;
    /**
     * Explicit Option A authorization. Without it, a primary-location-only
     * store-settings difference is an ordinary fail-closed collision — the
     * narrow merge rule is never available to arbitrary callers of this
     * generic service, only to a run presenting a code-owned policy bound to
     * this exact manifest.
     */
    primaryLocationMergeAuthorization?: PrimaryLocationMergeAuthorization;
  } = {},
): Promise<ApplyResult> {
  const report = await buildRemediationReport(manifest.scope, runner);

  if (manifest.reportVersion !== REMEDIATION_REPORT_VERSION) {
    throw new StaleReportError(
      `Manifest was generated by report version ${manifest.reportVersion}; this build produces ` +
        `${REMEDIATION_REPORT_VERSION}. Regenerate and re-review the report.`,
    );
  }

  // ── Whole-report authorization boundary ─────────────────────────────────
  // Approval was granted against the report as a whole, not just the approved
  // rows: a NEW duplicate group appearing in this scope, or a change to a group
  // the reviewer deliberately did NOT approve, changes what that approval meant.
  //
  // This is checked against the *unapproved remainder* rather than the raw
  // report hash. Applying an approved group legitimately changes the full-report
  // hash (its items become superseded), so comparing the full hash would make a
  // rerun — and any resume after a partially stopped run — look like drift and
  // destroy the idempotency guarantee. The remainder is unaffected by
  // remediating approved groups, so it isolates genuine third-party drift, while
  // the per-group hashes cover every approved group.
  if (!manifest.reportHash) {
    throw new StaleReportError('Manifest carries no report hash; regenerate and re-review it.');
  }
  if (!manifest.unapprovedReportHash) {
    throw new StaleReportError(
      'Manifest carries no unapproved-remainder hash; regenerate and re-review it.',
    );
  }
  // ── Option A authorization binding — before anything trusts it ───────────
  // Validated against THIS manifest's identity, hash, scope, and group count.
  // Fail closed: an invalid authorization refuses the run outright instead of
  // silently downgrading, so a binding mistake cannot masquerade as either
  // permission or a clean-but-blocked manifest.
  if (options.primaryLocationMergeAuthorization) {
    assertPrimaryLocationMergeAuthorization(options.primaryLocationMergeAuthorization, {
      scope: manifest.scope,
      manifestId: manifest.manifestId,
      reportHash: manifest.reportHash,
      groupCount: manifest.groups.length,
    });
  }

  const currentUnapprovedHash = computeUnapprovedRemainderHash(report, manifest.groups);
  if (currentUnapprovedHash !== manifest.unapprovedReportHash) {
    throw new StaleReportError(
      `The report changed outside the approved groups since review (approved remainder ` +
        `${manifest.unapprovedReportHash.slice(0, 12)}…, current ` +
        `${currentUnapprovedHash.slice(0, 12)}…). A duplicate group may have appeared or changed ` +
        `in this scope. Regenerate the report, re-review it, and rebuild the manifest.`,
    );
  }

  // ── Manifest-wide scope gate — before the first group is touched ──────────
  //
  // This is the invariant the suspended production run violated: it began
  // mutating an 848-group manifest and discovered cross-property external
  // mappings group by group, because scope was only ever checked per group at
  // mutation time. It stopped correctly and changed nothing, but only by luck of
  // ordering — a blocker in position 800 would have been found after 799 groups
  // were already committed.
  //
  // The gate previously lived only in the operator CLI, which left this function
  // callable directly with no gate at all. Any caller — a route, a script, a
  // future job — would get the old per-group behaviour. It belongs here, on the
  // mutation path itself, so the guarantee is a property of APPLY rather than of
  // one call site remembering to ask.
  //
  // Partial application is deliberately not offered. The reviewer approved this
  // manifest as a unit; applying its clean subset would substitute a scope
  // nobody signed off on. One blocker anywhere refuses the whole manifest, with
  // no writes and no audit rows.
  //
  // The CLI runs this same gate first for progress reporting and forensics. The
  // repeated evaluation is SELECT-only and this path is a rare operator action,
  // so paying for it twice is the right trade against a bypassable guarantee.
  await preflightManifestScope(
    manifest.scope,
    manifest.groups.map(group => ({
      sourceExternalId: group.sourceExternalId,
      canonicalItemId: group.canonicalItemId,
      supersededItemIds: group.supersededItemIds,
    })),
    runner,
    { legacyAdoptionAuthorization: options.legacyAdoptionAuthorization },
  );

  // ── Manifest-wide merge-content gate — same rule, second question ────────
  //
  // The scope gate above asks "does every group belong to the approved
  // scope?". The production run that passed it still stopped its first ten
  // groups on store-settings collisions, because merge-content blockers
  // (settings disagreements, unit-factor mismatches, count-line collisions)
  // were only ever discovered per group at mutation time. Same lesson, second
  // application: APPLY must never discover a deterministic merge-content
  // blocker that a read-only manifest-wide preflight could have discovered
  // first. This runs THE SAME pure decision functions the mutation path runs
  // (orderlyMergeContentPolicy), read-only, over every group, and refuses the
  // whole manifest if any group would stop. Transaction-time validation below
  // remains as defence in depth against concurrent change.
  await preflightManifestMergeContent(
    manifest.scope,
    manifest.groups.map(group => ({
      sourceExternalId: group.sourceExternalId,
      canonicalItemId: group.canonicalItemId,
      supersededItemIds: group.supersededItemIds,
    })),
    runner,
    { primaryLocationMergeAuthorization: options.primaryLocationMergeAuthorization },
  );

  const groupResults: ApplyGroupResult[] = [];
  const byCode = new Map(report.groups.map(group => [group.sourceExternalId, group]));

  for (const approval of manifest.groups) {
    const current = byCode.get(approval.sourceExternalId);

    // ── Freshness: has the group already been remediated? ─────────────────
    if (
      current &&
      current.classification === 'NOT_DEFECT_RELATED' &&
      current.proposedCanonicalItemId === approval.canonicalItemId &&
      current.candidates.some(candidate => candidate.supersededByItemId === approval.canonicalItemId)
    ) {
      const auditId = await writeAudit(runner, {
        manifest,
        approval,
        group: current,
        operatorId,
        result: 'already_remediated',
        failureReason: null,
        referencesMoved: { ...EMPTY_REFERENCE_COUNTS },
        valuationBefore: current.valuationContribution,
        valuationAfter: current.valuationContribution,
      });
      groupResults.push({
        sourceExternalId: approval.sourceExternalId,
        result: 'already_remediated',
        canonicalItemId: approval.canonicalItemId,
        supersededItemIds: approval.supersededItemIds,
        auditId,
      });
      continue;
    }

    // ── Staleness: the material facts must still match the manifest ────────
    const drift = detectDrift(manifest, approval, current);
    if (drift) {
      const auditId = current
        ? await writeAudit(runner, {
            manifest,
            approval,
            group: current,
            operatorId,
            result: 'stopped',
            failureReason: `${drift.code}: ${drift.reason}`,
            referencesMoved: { ...EMPTY_REFERENCE_COUNTS },
            valuationBefore: current.valuationContribution,
            valuationAfter: current.valuationContribution,
          })
        : null;
      groupResults.push({
        sourceExternalId: approval.sourceExternalId,
        result: 'stopped',
        failureCode: drift.code,
        failureReason: drift.reason,
        auditId,
      });
      continue;
    }

    const group = current!;

    try {
      // The repair and its audit record are ONE state transition. The audit row
      // is the only durable evidence that a group was remediated — discovery
      // reads it back to recognize a rerun as already-applied — so committing
      // the mutation without it would leave an applied but untracked repair that
      // cannot be resumed or reconciled. An audit-write failure must therefore
      // roll the whole group back, which means the insert (and the valuation it
      // records) runs inside the same transaction.
      const { referencesMoved, before, after, auditId } = await runner.transaction(
        async (tx: typeof db) => {
          // The drift check above ran OUTSIDE this transaction, so between it
          // and here another writer could change the evidence this repair acts
          // on and the repoint below would sweep it up as if it had been
          // reviewed. Lock the candidate items AND every dependent evidence row
          // BEFORE re-deriving the snapshot.
          //
          // Locking inventory_items alone is not enough, and this is the subtle
          // part: updating a count line's qty or unit cost does not touch, and
          // does not lock, the inventory item it points at. Such a writer would
          // sail past an items-only lock, commit after the under-lock recheck
          // read the old values, and have its new values repointed and audited
          // as though reviewed. The lock has to cover the rows whose VALUES the
          // snapshot binds, not just the rows the merge changes identity on.
          const candidateIds = [approval.canonicalItemId, ...approval.supersededItemIds];
          await lockGroupEvidence(tx, manifest.scope, candidateIds);

          // Scoped to THIS group's source code. The whole-scope invariants
          // (remainder hash, scope gate, merge-content gate) were proven once
          // above, immediately before mutation began; what must be revalidated
          // under the lock is only this group's own evidence. A group's facts
          // are derived exclusively from its code's rows/mappings/audits/
          // candidates, so the scoped rebuild yields the identical group
          // object — without re-running the other 800+ groups' discovery
          // queries inside every transaction (measured at ~65k queries/group,
          // the entire ~105 s/group production APPLY cost).
          const locked = await buildRemediationReport(manifest.scope, tx, {
            onlySourceCodes: [approval.sourceExternalId],
          });
          const lockedGroup = locked.groups.find(
            candidate => candidate.sourceExternalId === approval.sourceExternalId,
          );
          const lockedDrift = detectDrift(manifest, approval, lockedGroup);
          if (lockedDrift) {
            throw new Error(
              `${lockedDrift.code}: ${lockedDrift.reason} (detected under lock at mutation time — ` +
                'the group changed after it was reviewed)',
            );
          }

          // Everything below uses the snapshot re-derived UNDER the lock, never
          // the pre-transaction report object. The two are identical only
          // because the drift check just passed; using the stale one would let
          // the audit record a `valuationBefore` from before an edit that the
          // recheck accepted, describing a repair that did not happen.
          const lockedBefore = lockedGroup!.valuationContribution;
          const { moved, primaryLocationMerges } = await repointGroup(
            tx,
            manifest.scope,
            approval,
            lockedGroup!,
            options.legacyAdoptionAuthorization,
            options.primaryLocationMergeAuthorization !== undefined,
          );
          const valuationAfter = await recomputeGroupValuation(tx, manifest.scope.companyId, [
            approval.canonicalItemId,
            ...approval.supersededItemIds,
          ]);
          const writtenAuditId = await writeAudit(tx, {
            manifest,
            approval,
            group: lockedGroup!,
            operatorId,
            result: 'applied',
            failureReason: null,
            referencesMoved: moved,
            primaryLocationMerges,
            valuationBefore: lockedBefore,
            valuationAfter,
          });
          return {
            referencesMoved: moved,
            before: lockedBefore,
            after: valuationAfter,
            auditId: writtenAuditId,
          };
        },
        // Row locks cannot lock a row that does not exist yet. SERIALIZABLE
        // closes the phantom half: a concurrent INSERT of new evidence for this
        // group (a count line, a mapping, an import row) that would change the
        // outcome aborts one of the two transactions rather than slipping
        // between the locked snapshot and the repoint. Combined with the
        // explicit locks above — which make the common in-place UPDATE case
        // block rather than abort — the apply either sees the change in its
        // recheck and stops, or never sees it at all.
        { isolationLevel: 'serializable' },
      );

      const referencesUnchanged: ReferenceCounts = {
        ...EMPTY_REFERENCE_COUNTS,
        historicalInvoiceLines: group.referencesToRepoint.historicalInvoiceLines,
      };

      groupResults.push({
        sourceExternalId: approval.sourceExternalId,
        result: 'applied',
        canonicalItemId: approval.canonicalItemId,
        supersededItemIds: approval.supersededItemIds,
        referencesMoved,
        referencesUnchanged,
        valuationBefore: before,
        valuationAfter: after,
        valuationDelta: round2(after - before),
        auditId,
      });
    } catch (error) {
      const failureCode = classifyFailure(error);
      const reason = describeFailure(error);
      const auditId = await writeAudit(runner, {
        manifest,
        approval,
        group,
        operatorId,
        result: 'stopped',
        failureReason: `${failureCode}: ${reason}`,
        referencesMoved: { ...EMPTY_REFERENCE_COUNTS },
        // The group was not mutated, so before == after. Both come from the
        // pre-transaction read: a stop can be raised before the locked snapshot
        // exists (or by the recheck itself), and this only records that nothing
        // moved.
        valuationBefore: group.valuationContribution,
        valuationAfter: group.valuationContribution,
      });
      groupResults.push({
        sourceExternalId: approval.sourceExternalId,
        result: 'stopped',
        failureCode,
        failureReason: reason,
        auditId,
      });
    }
  }

  return {
    manifestId: manifest.manifestId,
    reportHash: manifest.reportHash,
    scope: manifest.scope,
    applied: groupResults.filter(result => result.result === 'applied').length,
    alreadyRemediated: groupResults.filter(result => result.result === 'already_remediated').length,
    stopped: groupResults.filter(result => result.result === 'stopped').length,
    groups: groupResults,
  };
}

function detectDrift(
  manifest: ApplyManifest,
  approval: ManifestGroupApproval,
  current: RemediationGroup | undefined,
): { code: StopCode; reason: string } | null {
  if (!current) {
    return {
      code: 'STALE_REPORT',
      reason: `source code ${approval.sourceExternalId} no longer produces a duplicate group in this scope`,
    };
  }
  if (current.classification !== 'SAFE_CANDIDATE') {
    return {
      code: current.classification === 'CONFLICT' ? 'STALE_REPORT' : 'NOT_SAFE_CANDIDATE',
      reason:
        `group ${approval.sourceExternalId} is now ${current.classification}` +
        (current.evidence.conflictReasons.length > 0
          ? ` (${current.evidence.conflictReasons.join('; ')})`
          : '') +
        (current.evidence.ambiguityReasons.length > 0
          ? ` (${current.evidence.ambiguityReasons.join('; ')})`
          : ''),
    };
  }
  if (current.proposedCanonicalItemId !== approval.canonicalItemId) {
    return {
      code: 'STALE_REPORT',
      reason:
        `approved canonical ${approval.canonicalItemId} but the current evidence proposes ` +
        `${current.proposedCanonicalItemId}`,
    };
  }
  const approvedSuperseded = [...approval.supersededItemIds].sort().join(',');
  const currentSuperseded = [...current.alternativeCandidateIds].sort().join(',');
  if (approvedSuperseded !== currentSuperseded) {
    return {
      code: 'STALE_REPORT',
      reason: `approved duplicates [${approvedSuperseded}] but the current candidates are [${currentSuperseded}]`,
    };
  }
  if (!manifest.reportHash) {
    return { code: 'MANIFEST_MISMATCH', reason: 'manifest carries no report hash' };
  }
  if (!approval.groupHash) {
    return {
      code: 'MANIFEST_MISMATCH',
      reason: `approved group ${approval.sourceExternalId} carries no group hash`,
    };
  }
  // Final catch-all: any material change the explicit checks above did not name
  // still invalidates the approval, because the reviewer approved this exact
  // evidence.
  const currentHash = computeReportHash(manifest.scope, [current]);
  if (currentHash !== approval.groupHash) {
    return {
      code: 'STALE_REPORT',
      reason:
        `group ${approval.sourceExternalId} no longer matches the reviewed evidence ` +
        `(approved ${approval.groupHash.slice(0, 12)}…, current ${currentHash.slice(0, 12)}…)`,
    };
  }
  return null;
}

/**
 * Renders an error for the audit trail.
 *
 * Driver errors surface as "Failed query: <the entire SQL and its params>" with
 * the actual database message hidden on `cause`. That is unreadable in an audit
 * row an operator has to interpret months later, so the underlying cause is
 * pulled to the front and the query dump is dropped.
 */
function describeFailure(error: unknown): string {
  if (!(error instanceof Error)) return String(error);
  const causes: string[] = [];
  let cursor: unknown = (error as { cause?: unknown }).cause;
  const seen = new Set<unknown>();
  while (cursor instanceof Error && !seen.has(cursor)) {
    seen.add(cursor);
    causes.push(cursor.message);
    cursor = (cursor as { cause?: unknown }).cause;
  }
  const deepest = causes.length > 0 ? causes[causes.length - 1] : null;
  if (!deepest) {
    // No cause chain: keep the message, but do not let a giant query dump land
    // in the audit row.
    const [firstLine] = error.message.split('\n');
    return firstLine.length > 500 ? `${firstLine.slice(0, 500)}…` : firstLine;
  }
  return deepest;
}

function classifyFailure(error: unknown): StopCode {
  // Classify on the unwrapped cause as well as the wrapper: a driver error hides
  // the real constraint message on `cause`, so matching only the top-level
  // message would misclassify every collision as UNEXPECTED_REFERENCE.
  const message =
    (error instanceof Error ? error.message : String(error)) + '\n' + describeFailure(error);
  if (/OUT_OF_SCOPE_REFERENCE/.test(message)) return 'OUT_OF_SCOPE_REFERENCE';
  // A serialization failure (SQLSTATE 40001) means a concurrent writer inserted
  // evidence this group depends on. Postgres aborted us rather than let the
  // repair act on rows the snapshot never saw, which is exactly the freshness
  // guarantee — so record it as STALE_REPORT, not as an unexpected reference.
  // Deliberately NOT retried: a retry would re-derive and re-apply without a
  // human re-reading the changed evidence.
  if (
    /40001/.test(message) ||
    /could not serialize|serialization failure/i.test(message)
  ) {
    return 'STALE_REPORT';
  }
  // A stop raised by the under-lock freshness recheck already carries its own
  // code; keep it rather than flattening it to UNEXPECTED_REFERENCE, so the
  // audit row distinguishes "someone edited this concurrently" from "the repair
  // hit something it did not expect".
  if (/^STALE_REPORT|\bSTALE_REPORT:/.test(message)) return 'STALE_REPORT';
  if (/^MANIFEST_MISMATCH|\bMANIFEST_MISMATCH:/.test(message)) return 'MANIFEST_MISMATCH';
  if (/^NOT_SAFE_CANDIDATE|\bNOT_SAFE_CANDIDATE:/.test(message)) return 'NOT_SAFE_CANDIDATE';
  if (/immutable/i.test(message)) return 'IMMUTABLE_EVIDENCE';
  if (/duplicate key|unique constraint|uniqueness/i.test(message)) return 'UNIQUENESS_COLLISION';
  return 'UNEXPECTED_REFERENCE';
}

/**
 * The single mutation path. Runs inside the caller's transaction so any throw
 * rolls the whole group back.
 *
 * Historical count evidence is repointed only: quantity, unit cost, case/
 * container/loose breakdown, storage location, unit, user, and countedAt stay
 * exactly as recorded, and the count session keeps its source batch identity.
 */
async function repointGroup(
  tx: typeof db,
  scope: RemediationScope,
  approval: ManifestGroupApproval,
  group: RemediationGroup,
  legacyAdoptionAuthorization?: LegacyAdoptionAuthorization,
  primaryLocationMergeAuthorized = false,
): Promise<RepointOutcome> {
  const { canonicalItemId, supersededItemIds } = approval;
  const duplicateIds = supersededItemIds;
  const moved = { ...EMPTY_REFERENCE_COUNTS };
  const primaryLocationMerges: PrimaryLocationMergeRecord[] = [];

  if (duplicateIds.length === 0) return { moved, primaryLocationMerges };

  // Deterministic duplicate processing order: the manifest's supersededItemIds
  // order, NOT the database's arbitrary return order. Sequential merging makes
  // an earlier duplicate's repointed row the baseline every later duplicate is
  // compared against, so the order decides which value is retained when the
  // canonical has no row for a key. The manifest-wide merge preflight sorts by
  // the same key, so what it predicts (including retained/discarded primary
  // locations in its merge records) is exactly what APPLY does.
  const duplicateOrder = new Map(duplicateIds.map((id, index) => [id, index]));
  const byManifestOrder = <T extends { inventoryItemId: string }>(rows: T[]): T[] =>
    [...rows].sort(
      (a, b) =>
        (duplicateOrder.get(a.inventoryItemId) ?? -1) -
        (duplicateOrder.get(b.inventoryItemId) ?? -1),
    );

  // Re-assert ownership inside the transaction.
  const owned = (await tx
    .select({ id: inventoryItems.id })
    .from(inventoryItems)
    .where(
      and(
        inArray(inventoryItems.id, [canonicalItemId, ...duplicateIds]),
        eq(inventoryItems.companyId, scope.companyId),
      ),
    )) as Array<{ id: string }>;
  if (owned.length !== duplicateIds.length + 1) {
    throw new Error(
      'candidate items are not all owned by the scoped company at mutation time',
    );
  }

  // Defence in depth. Manifest-aware preflight has already run this exact
  // decision over every group in the manifest and refused the whole manifest if
  // any group failed — but preflight proved the manifest was clean when it ran,
  // not that it is still clean now. This re-runs THE SAME shared validator
  // inside the serializable transaction, under the evidence locks taken above,
  // so a boundary that moved after preflight stops the group before mutation.
  //
  // If this ever fires for a manifest a just-completed preflight passed against
  // unchanged data, that is a correctness defect in the shared validator, not a
  // routine stop — the two call sites run the same code over the same evidence.
  await assertGroupExclusiveToScope(
    tx,
    scope,
    [canonicalItemId, ...duplicateIds],
    approval.sourceExternalId,
    legacyAdoptionAuthorization,
  );

  // Immutable evidence must never be touched.
  const [invoiceEvidence] = (await tx
    .select({ n: sql<number>`count(*)` })
    .from(historicalInvoiceLines)
    .where(
      and(
        eq(historicalInvoiceLines.companyId, scope.companyId),
        inArray(historicalInvoiceLines.inventoryItemId, duplicateIds),
      ),
    )) as Array<{ n: number | string }>;
  if (Number(invoiceEvidence?.n ?? 0) > 0) {
    throw new Error(
      'immutable historical invoice evidence references a duplicate item; refusing to repoint',
    );
  }

  // ── 1. Count lines — repoint only, never merge or recalculate ────────────
  // unique(inventoryCountId, inventoryItemId, storageLocationId): a real
  // collision means two legitimate rows would have to become one. Stop instead
  // of aggregating or deleting history.
  const dupeCountLines = byManifestOrder(
    (await tx
      .select({
        id: inventoryCountLines.id,
        inventoryItemId: inventoryCountLines.inventoryItemId,
        inventoryCountId: inventoryCountLines.inventoryCountId,
        storageLocationId: inventoryCountLines.storageLocationId,
      })
      .from(inventoryCountLines)
      .where(inArray(inventoryCountLines.inventoryItemId, duplicateIds))) as Array<{
      id: string;
      inventoryItemId: string;
      inventoryCountId: string;
      storageLocationId: string;
    }>,
  );

  const canonicalCountKeys = new Set(
    (
      (await tx
        .select({
          inventoryCountId: inventoryCountLines.inventoryCountId,
          storageLocationId: inventoryCountLines.storageLocationId,
        })
        .from(inventoryCountLines)
        .where(eq(inventoryCountLines.inventoryItemId, canonicalItemId))) as Array<{
        inventoryCountId: string;
        storageLocationId: string;
      }>
    ).map(row => `${row.inventoryCountId}::${row.storageLocationId}`),
  );

  const seen = new Set<string>();
  for (const line of dupeCountLines) {
    const key = `${line.inventoryCountId}::${line.storageLocationId}`;
    if (canonicalCountKeys.has(key) || seen.has(key)) {
      throw new Error(
        'UNIQUENESS_COLLISION: count session ' +
          `${line.inventoryCountId} storage location ${line.storageLocationId} already has a ` +
          `count row on canonical item ${canonicalItemId}. Two legitimate count rows cannot share ` +
          'one canonical identity without aggregating history — stopping this group.',
      );
    }
    seen.add(key);
  }

  if (dupeCountLines.length > 0) {
    await tx
      .update(inventoryCountLines)
      .set({ inventoryItemId: canonicalItemId })
      .where(
        inArray(
          inventoryCountLines.id,
          dupeCountLines.map(line => line.id),
        ),
      );
    moved.inventoryCountLines = dupeCountLines.length;
  }

  // ── 2. Store inventory — union ONLY when the store settings agree ────────
  // unique(storeId, inventoryItemId) does not cover primaryLocationId,
  // parLevel, reorderLevel, or active. Those are live per-store manager
  // settings, so dropping the duplicate's row because the key matches would
  // discard them with no conflict and no human decision.
  //
  // onHandQty is deliberately EXCLUDED from this comparison: it is derived from
  // the applied count, which this same transaction repoints onto the canonical
  // item. Summing it would double-count and comparing it would stop nearly
  // every real group, so the canonical row's quantity stands and the count
  // history remains the source of truth.
  // When the ONLY difference is primaryLocationId, the PM-approved narrow rule
  // (Option A) applies: retain the canonical's primary, discard the
  // duplicate's, record the discarded value in the audit evidence, and prove
  // the discarded location survives in the merged location union. This exists
  // because Orderly created per-location item variants, so a primary-location
  // disagreement is inherent to the duplicate population rather than a live
  // manager decision being silently overwritten. It is deliberately NOT a
  // general canonical-wins policy: any other protected-field difference still
  // stops the group.
  // Stores where the CANONICAL itself has a row right now. The Option A rule
  // retains the canonical's primary, so it applies only against a genuine
  // canonical-origin row: a primary-location disagreement against a row that
  // arrived by repointing an earlier duplicate (canonical-absent shape) has no
  // approved retention source and fails closed.
  const canonicalStoreIds = new Set(
    (
      (await tx
        .select({ storeId: storeInventoryItems.storeId })
        .from(storeInventoryItems)
        .where(eq(storeInventoryItems.inventoryItemId, canonicalItemId))) as Array<{
        storeId: string;
      }>
    ).map(row => row.storeId),
  );

  const dupeStoreRows = byManifestOrder(
    (await tx
      .select({
        id: storeInventoryItems.id,
        storeId: storeInventoryItems.storeId,
        inventoryItemId: storeInventoryItems.inventoryItemId,
        primaryLocationId: storeInventoryItems.primaryLocationId,
        parLevel: storeInventoryItems.parLevel,
        reorderLevel: storeInventoryItems.reorderLevel,
        active: storeInventoryItems.active,
      })
      .from(storeInventoryItems)
      .where(inArray(storeInventoryItems.inventoryItemId, duplicateIds))) as Array<{
      id: string;
      storeId: string;
      inventoryItemId: string;
      primaryLocationId: string | null;
      parLevel: number | null;
      reorderLevel: number | null;
      active: number;
    }>,
  );
  for (const row of dupeStoreRows) {
    const [existing] = (await tx
      .select({
        id: storeInventoryItems.id,
        primaryLocationId: storeInventoryItems.primaryLocationId,
        parLevel: storeInventoryItems.parLevel,
        reorderLevel: storeInventoryItems.reorderLevel,
        active: storeInventoryItems.active,
      })
      .from(storeInventoryItems)
      .where(
        and(
          eq(storeInventoryItems.storeId, row.storeId),
          eq(storeInventoryItems.inventoryItemId, canonicalItemId),
        ),
      )) as Array<{
      id: string;
      primaryLocationId: string | null;
      parLevel: number | null;
      reorderLevel: number | null;
      active: number;
    }>;
    if (existing) {
      const decision = decideStoreSettingsMerge(existing, row);
      if (decision.kind === 'conflict') {
        throw new Error(
          `UNIQUENESS_COLLISION: store inventory settings for store ${row.storeId} differ ` +
            `between canonical item ${canonicalItemId} and a duplicate ` +
            `(${decision.differences.join('; ')}). Merging would silently discard live store ` +
            'configuration — stopping this group for manual reconciliation.',
        );
      }
      if (decision.kind === 'primary_location_only') {
        if (!primaryLocationMergeAuthorized) {
          throw new Error(
            `UNIQUENESS_COLLISION: store row for store ${row.storeId} differs only on primary ` +
              'location, but no Option A primary-location merge authorization was provided. The ' +
              'narrow merge rule is bound to one approved manifest population — without the ' +
              'authorization this remains a fail-closed collision.',
          );
        }
        if (!canonicalStoreIds.has(row.storeId)) {
          throw new Error(
            `UNIQUENESS_COLLISION: canonical item ${canonicalItemId} has no store row for store ` +
              `${row.storeId}; the conflicting row arrived from an earlier duplicate. The ` +
              "approved Option A rule retains the CANONICAL's primary, so with no canonical row " +
              'there is no approved retention source — stopping this group pending explicit ' +
              'approval of this shape.',
          );
        }
        const survives = await discardedPrimaryLocationSurvives(
          tx,
          [canonicalItemId, ...duplicateIds],
          decision.discardedPrimaryLocationId,
        );
        if (!survives) {
          throw new Error(
            `UNIQUENESS_COLLISION: store row for store ${row.storeId} differs only on primary ` +
              `location (${decision.retainedPrimaryLocationId ?? 'unset'} vs ` +
              `${decision.discardedPrimaryLocationId ?? 'unset'}), but the duplicate's primary ` +
              `location ${decision.discardedPrimaryLocationId} is not represented anywhere in ` +
              'the merged location union — discarding it would make that location disappear ' +
              'from the item entirely. Stopping this group for manual reconciliation.',
          );
        }
        primaryLocationMerges.push({
          storeId: row.storeId,
          canonicalItemId,
          supersededItemId: row.inventoryItemId,
          retainedPrimaryLocationId: decision.retainedPrimaryLocationId,
          discardedPrimaryLocationId: decision.discardedPrimaryLocationId,
          otherProtectedSettingsMatched: true,
          locationUnionPreserved: true,
        });
      }
      await tx.delete(storeInventoryItems).where(eq(storeInventoryItems.id, row.id));
    } else {
      await tx
        .update(storeInventoryItems)
        .set({ inventoryItemId: canonicalItemId })
        .where(eq(storeInventoryItems.id, row.id));
    }
    moved.storeInventoryItems++;
  }

  // ── 3. Location assignments — union ONLY when the rows agree ─────────────
  // unique(inventoryItemId, locationId) does not cover parTarget, isPrimary, or
  // active. Dropping the duplicate's row because the key matches would silently
  // discard a different par target or primary designation — live configuration
  // a manager set deliberately. Identical rows are genuinely redundant and are
  // dropped; any disagreement stops the group for a human decision.
  const dupeAssignments = byManifestOrder(
    (await tx
      .select({
        id: inventoryItemLocationAssignments.id,
        inventoryItemId: inventoryItemLocationAssignments.inventoryItemId,
        locationId: inventoryItemLocationAssignments.locationId,
        parTarget: inventoryItemLocationAssignments.parTarget,
        isPrimary: inventoryItemLocationAssignments.isPrimary,
        active: inventoryItemLocationAssignments.active,
      })
      .from(inventoryItemLocationAssignments)
      .where(inArray(inventoryItemLocationAssignments.inventoryItemId, duplicateIds))) as Array<{
      id: string;
      inventoryItemId: string;
      locationId: string;
      parTarget: number | null;
      isPrimary: number;
      active: number;
    }>,
  );
  for (const assignment of dupeAssignments) {
    const [existing] = (await tx
      .select({
        id: inventoryItemLocationAssignments.id,
        parTarget: inventoryItemLocationAssignments.parTarget,
        isPrimary: inventoryItemLocationAssignments.isPrimary,
        active: inventoryItemLocationAssignments.active,
      })
      .from(inventoryItemLocationAssignments)
      .where(
        and(
          eq(inventoryItemLocationAssignments.inventoryItemId, canonicalItemId),
          eq(inventoryItemLocationAssignments.locationId, assignment.locationId),
        ),
      )) as Array<{
      id: string;
      parTarget: number | null;
      isPrimary: number;
      active: number;
    }>;
    if (existing) {
      const differences = assignmentDifferences(existing, assignment);
      if (differences.length > 0) {
        throw new Error(
          'UNIQUENESS_COLLISION: location assignment for location ' +
            `${assignment.locationId} differs between canonical item ${canonicalItemId} and a ` +
            `duplicate (${differences.join('; ')}). Merging would silently discard live ` +
            'configuration — stopping this group for manual reconciliation.',
        );
      }
      await tx
        .delete(inventoryItemLocationAssignments)
        .where(eq(inventoryItemLocationAssignments.id, assignment.id));
    } else {
      await tx
        .update(inventoryItemLocationAssignments)
        .set({ inventoryItemId: canonicalItemId })
        .where(eq(inventoryItemLocationAssignments.id, assignment.id));
    }
    moved.inventoryItemLocationAssignments++;
  }

  // ── 3b. Legacy item-location rows — union on (item, storage location) ─────
  // inventory_item_locations is deprecated in favour of store_inventory_items,
  // but storage.ts still inner-joins it when filtering items by location. A row
  // left behind on a superseded item would keep that item visible in those
  // reads, so it is unioned onto the canonical exactly like the assignments
  // above rather than being ignored.
  // isPrimary is the only value this table carries beyond the key, so it gets
  // the same treatment as every other merge: equal rows are redundant, a
  // differing primary designation stops the group.
  const dupeLegacyLocations = byManifestOrder(
    (await tx
      .select({
        id: inventoryItemLocations.id,
        inventoryItemId: inventoryItemLocations.inventoryItemId,
        storageLocationId: inventoryItemLocations.storageLocationId,
        isPrimary: inventoryItemLocations.isPrimary,
      })
      .from(inventoryItemLocations)
      .where(inArray(inventoryItemLocations.inventoryItemId, duplicateIds))) as Array<{
      id: string;
      inventoryItemId: string;
      storageLocationId: string;
      isPrimary: number;
    }>,
  );
  for (const legacy of dupeLegacyLocations) {
    const [existing] = (await tx
      .select({
        id: inventoryItemLocations.id,
        isPrimary: inventoryItemLocations.isPrimary,
      })
      .from(inventoryItemLocations)
      .where(
        and(
          eq(inventoryItemLocations.inventoryItemId, canonicalItemId),
          eq(inventoryItemLocations.storageLocationId, legacy.storageLocationId),
        ),
      )) as Array<{ id: string; isPrimary: number }>;
    if (existing) {
      if (legacyLocationDifferences(existing, legacy).length > 0) {
        throw new Error(
          'UNIQUENESS_COLLISION: legacy item-location row for storage location ' +
            `${legacy.storageLocationId} has primary flag ${existing.isPrimary} on canonical item ` +
            `${canonicalItemId} but ${legacy.isPrimary} on a duplicate. Merging would silently ` +
            'change which location is primary — stopping this group for manual reconciliation.',
        );
      }
      await tx.delete(inventoryItemLocations).where(eq(inventoryItemLocations.id, legacy.id));
    } else {
      await tx
        .update(inventoryItemLocations)
        .set({ inventoryItemId: canonicalItemId })
        .where(eq(inventoryItemLocations.id, legacy.id));
    }
    moved.inventoryItemLocations++;
  }

  // ── 4. External mappings — consolidate onto the canonical identity ───────
  // unique(company, source system, source property, external code) means at
  // most one row per identity claim, so a duplicate's mapping is either
  // repointed or removed once the canonical claim exists.
  const dupeMappings = (await tx
    .select({
      id: inventoryItemExternalMappings.id,
      sourceSystem: inventoryItemExternalMappings.sourceSystem,
      sourcePropertyId: inventoryItemExternalMappings.sourcePropertyId,
      sourceExternalId: inventoryItemExternalMappings.sourceExternalId,
    })
    .from(inventoryItemExternalMappings)
    .where(
      and(
        eq(inventoryItemExternalMappings.companyId, scope.companyId),
        inArray(inventoryItemExternalMappings.inventoryItemId, duplicateIds),
      ),
    )) as Array<{
    id: string;
    sourceSystem: string;
    sourcePropertyId: string;
    sourceExternalId: string;
  }>;
  for (const mapping of dupeMappings) {
    const [existing] = (await tx
      .select({ id: inventoryItemExternalMappings.id })
      .from(inventoryItemExternalMappings)
      .where(
        and(
          eq(inventoryItemExternalMappings.companyId, scope.companyId),
          eq(inventoryItemExternalMappings.sourceSystem, mapping.sourceSystem),
          eq(inventoryItemExternalMappings.sourcePropertyId, mapping.sourcePropertyId),
          eq(inventoryItemExternalMappings.sourceExternalId, mapping.sourceExternalId),
          eq(inventoryItemExternalMappings.inventoryItemId, canonicalItemId),
        ),
      )) as Array<{ id: string }>;
    if (existing) {
      await tx
        .delete(inventoryItemExternalMappings)
        .where(eq(inventoryItemExternalMappings.id, mapping.id));
    } else {
      await tx
        .update(inventoryItemExternalMappings)
        .set({ inventoryItemId: canonicalItemId })
        .where(eq(inventoryItemExternalMappings.id, mapping.id));
    }
    moved.inventoryItemExternalMappings++;
  }

  // ── 5. Import-row provenance — repoint so the trail leads to the canonical
  // item, without touching rawData, counts, or batch identity.
  const importRowUpdate = await tx
    .update(inventoryImportRows)
    .set({ resolvedInventoryItemId: canonicalItemId })
    .where(inArray(inventoryImportRows.resolvedInventoryItemId, duplicateIds));
  moved.inventoryImportRows = (importRowUpdate as { rowCount?: number }).rowCount ?? 0;

  // ── 6. Item units — union ONLY when the conversion factor agrees ─────────
  // unique(inventoryItemId, unitId, isIssueUnit) does not cover
  // unitsPerCanonical, which is the conversion factor recipe and transfer
  // costing divide by. Two rows can share the key and still mean different
  // things ("1 case = 6" vs "1 case = 12"); dropping one because the key
  // matches would silently change every downstream cost. Identical factors are
  // redundant and dropped; a mismatch stops the group.
  const dupeUnits = byManifestOrder(
    (await tx
      .select({
        id: inventoryItemUnits.id,
        inventoryItemId: inventoryItemUnits.inventoryItemId,
        unitId: inventoryItemUnits.unitId,
        isIssueUnit: inventoryItemUnits.isIssueUnit,
        unitsPerCanonical: inventoryItemUnits.unitsPerCanonical,
      })
      .from(inventoryItemUnits)
      .where(inArray(inventoryItemUnits.inventoryItemId, duplicateIds))) as Array<{
      id: string;
      inventoryItemId: string;
      unitId: string;
      isIssueUnit: number;
      unitsPerCanonical: number;
    }>,
  );
  for (const unitRow of dupeUnits) {
    const [existing] = (await tx
      .select({
        id: inventoryItemUnits.id,
        unitsPerCanonical: inventoryItemUnits.unitsPerCanonical,
      })
      .from(inventoryItemUnits)
      .where(
        and(
          eq(inventoryItemUnits.inventoryItemId, canonicalItemId),
          eq(inventoryItemUnits.unitId, unitRow.unitId),
          eq(inventoryItemUnits.isIssueUnit, unitRow.isIssueUnit),
        ),
      )) as Array<{ id: string; unitsPerCanonical: number }>;
    if (existing) {
      if (unitDifferences(existing, unitRow).length > 0) {
        throw new Error(
          `UNIQUENESS_COLLISION: unit ${unitRow.unitId} (isIssueUnit=${unitRow.isIssueUnit}) has ` +
            `conversion factor ${fmt(existing.unitsPerCanonical)} on canonical item ` +
            `${canonicalItemId} but ${fmt(unitRow.unitsPerCanonical)} on a duplicate. Merging ` +
            'would silently change recipe and transfer costing — stopping this group for manual ' +
            'reconciliation.',
        );
      }
      await tx.delete(inventoryItemUnits).where(eq(inventoryItemUnits.id, unitRow.id));
    } else {
      await tx
        .update(inventoryItemUnits)
        .set({ inventoryItemId: canonicalItemId })
        .where(eq(inventoryItemUnits.id, unitRow.id));
    }
    moved.inventoryItemUnits++;
  }

  // ── 7. Remaining plain-FK references ────────────────────────────────────
  const simpleRepoints: Array<[keyof ReferenceCounts, () => Promise<unknown>]> = [
    [
      'inventoryItemPriceHistory',
      () =>
        tx
          .update(inventoryItemPriceHistory)
          .set({ inventoryItemId: canonicalItemId })
          .where(inArray(inventoryItemPriceHistory.inventoryItemId, duplicateIds)),
    ],
    [
      'vendorItems',
      () =>
        tx
          .update(vendorItems)
          .set({ inventoryItemId: canonicalItemId })
          .where(inArray(vendorItems.inventoryItemId, duplicateIds)),
    ],
    [
      'recipeComponents',
      () =>
        tx
          .update(recipeComponents)
          .set({ componentId: canonicalItemId })
          .where(
            and(
              eq(recipeComponents.componentType, 'inventory_item'),
              inArray(recipeComponents.componentId, duplicateIds),
            ),
          ),
    ],
    [
      'theoreticalUsageLines',
      () =>
        tx
          .update(theoreticalUsageLines)
          .set({ inventoryItemId: canonicalItemId })
          .where(inArray(theoreticalUsageLines.inventoryItemId, duplicateIds)),
    ],
    [
      'transferLogs',
      () =>
        tx
          .update(transferLogs)
          .set({ inventoryItemId: canonicalItemId })
          .where(inArray(transferLogs.inventoryItemId, duplicateIds)),
    ],
    [
      'transferOrderLines',
      () =>
        tx
          .update(transferOrderLines)
          .set({ inventoryItemId: canonicalItemId })
          .where(inArray(transferOrderLines.inventoryItemId, duplicateIds)),
    ],
    [
      'wasteLogs',
      () =>
        tx
          .update(wasteLogs)
          .set({ inventoryItemId: canonicalItemId })
          .where(inArray(wasteLogs.inventoryItemId, duplicateIds)),
    ],
    [
      'orderGuideLinesMatched',
      () =>
        tx
          .update(orderGuideLines)
          .set({ matchedInventoryItemId: canonicalItemId })
          .where(inArray(orderGuideLines.matchedInventoryItemId, duplicateIds)),
    ],
    [
      'orderGuideLinesCreated',
      () =>
        tx
          .update(orderGuideLines)
          .set({ createdInventoryItemId: canonicalItemId })
          .where(inArray(orderGuideLines.createdInventoryItemId, duplicateIds)),
    ],
  ];
  for (const [key, run] of simpleRepoints) {
    const result = await run();
    moved[key] = (result as { rowCount?: number }).rowCount ?? 0;
  }

  // po_routing_audit is an append-only audit of what was actually routed at the
  // time. It keeps pointing at the identity that was used, and is reported as
  // unchanged rather than rewritten.
  moved.poRoutingAudit = 0;

  // ── 8. Supersede, never delete ──────────────────────────────────────────
  await tx
    .update(inventoryItems)
    .set({
      active: 0,
      supersededByItemId: canonicalItemId,
      supersededAt: new Date(),
      supersededReason:
        `Orderly ${scope.sourceSystem} item code ${approval.sourceExternalId} duplicate identity ` +
        `remediation (source property ${scope.sourcePropertyId || 'legacy'})`,
      updatedAt: new Date(),
    })
    .where(
      and(inArray(inventoryItems.id, duplicateIds), eq(inventoryItems.companyId, scope.companyId)),
    );

  // Sanity: after repointing, no duplicate may retain a mutable reference.
  for (const duplicateId of duplicateIds) {
    const remaining = await countReferences(tx, scope.companyId, duplicateId);
    const mutableRemaining =
      sumReferences(remaining) - remaining.historicalInvoiceLines - remaining.poRoutingAudit;
    if (mutableRemaining > 0) {
      throw new Error(
        `duplicate item ${duplicateId} still has ${mutableRemaining} mutable reference(s) after ` +
          `repointing: ${JSON.stringify(remaining)}`,
      );
    }
  }

  // ── 9. Re-derive store on-hand from the repointed count history ──────────
  await recomputeStoreOnHand(tx, scope, canonicalItemId);

  void group;
  return { moved, primaryLocationMerges };
}

/** What repointGroup did, for the audit row and the apply result. */
interface RepointOutcome {
  moved: ReferenceCounts;
  /** Store rows merged under the approved primary-location-only rule. */
  primaryLocationMerges: PrimaryLocationMergeRecord[];
}

/**
 * The location-preservation invariant of the approved primary-location-only
 * merge rule: the duplicate's discarded primary location must remain
 * represented on the merged canonical identity, so a location never disappears
 * because the identity that named it primary was superseded.
 *
 * Representation is checked across the modern assignment table AND the legacy
 * item-location table, over the canonical plus all duplicates — duplicate rows
 * are unioned onto the canonical later in the same transaction, and any
 * disagreement in that union stops the whole group before commit, so a row
 * found here is guaranteed to survive on the canonical or the group never
 * commits at all.
 *
 * A discarded NULL primary ("unset") names no location, so there is nothing to
 * preserve.
 *
 * SELECT-only; both the mutation path and the read-only merge preflight call
 * it so eligibility means the same thing in both places.
 */
async function discardedPrimaryLocationSurvives(
  runner: typeof db,
  itemIds: string[],
  discardedPrimaryLocationId: string | null,
): Promise<boolean> {
  if (discardedPrimaryLocationId === null) return true;
  const [assignment] = (await runner
    .select({ id: inventoryItemLocationAssignments.id })
    .from(inventoryItemLocationAssignments)
    .where(
      and(
        inArray(inventoryItemLocationAssignments.inventoryItemId, itemIds),
        eq(inventoryItemLocationAssignments.locationId, discardedPrimaryLocationId),
      ),
    )
    .limit(1)) as Array<{ id: string }>;
  if (assignment) return true;
  const [legacy] = (await runner
    .select({ id: inventoryItemLocations.id })
    .from(inventoryItemLocations)
    .where(
      and(
        inArray(inventoryItemLocations.inventoryItemId, itemIds),
        eq(inventoryItemLocations.storageLocationId, discardedPrimaryLocationId),
      ),
    )
    .limit(1)) as Array<{ id: string }>;
  return Boolean(legacy);
}

/**
 * Refuses the group unless every scoped reference on its items belongs to the
 * approved store and source property.
 *
 * The ownership model: approval is granted for ONE Orderly source property's
 * data at ONE store. Discovery already restricts which items become candidates,
 * but repointing rewrites references by item id, and an inventory item is a
 * company-level record — the same row can legitimately carry a store inventory
 * row for a second store, a mapping for a second Orderly property, or import
 * history from a batch nobody approved here. Repointing those would let a
 * Bay-Hill-scoped approval silently rewrite another property's data.
 *
 * Where a reference carries provenance, it must match the scope:
 *   - store_inventory_items / waste_logs / transfer_logs — carry a store id.
 *   - inventory_item_external_mappings — carry source system + property; this
 *     is the identity binding, so a foreign-property mapping means the item is
 *     shared between properties and cannot be merged under this approval.
 *   - inventory_import_rows — reachable only through their batch, so scope is
 *     checked by joining to the approved batch set.
 *   - inventory_count_lines — reachable through their session's store.
 *
 * Anything found outside the scope STOPS the group with no mutation, rather
 * than being filtered out and partially repointed: a half-merged item whose
 * remaining references still point at the duplicate is a worse state than an
 * untouched one, and the decision belongs to a human.
 *
 * References with no scope provenance at all (vendor items, price history,
 * recipe components, usage lines, transfer order lines) are company-level by
 * construction and are handled by the existing collision checks.
 */
/**
 * Takes row locks on the candidate items AND every dependent row whose values
 * the approval binds, before the locked snapshot is derived.
 *
 * Locking `inventory_items` alone does not protect this repair. Updating a
 * count line's qty or unit cost, a unit conversion factor, or a store par level
 * neither touches nor locks the inventory item those rows point at, so such a
 * writer would pass straight through an items-only lock, commit after the
 * under-lock recheck had already read the old values, and have its new values
 * repointed and audited as if reviewed. The lock must cover the rows whose
 * VALUES the snapshot hashes, not just the rows whose identity the merge
 * rewrites.
 *
 * Locks are acquired in a fixed table order, and each statement orders its rows
 * by id, so two concurrent applies touching overlapping groups queue up instead
 * of deadlocking.
 *
 * Row locks alone cannot stop a row that does not exist yet (a phantom), which
 * is why the enclosing transaction also runs at SERIALIZABLE: an insert into
 * this group's evidence that would change the outcome surfaces as a
 * serialization failure and stops the group.
 */
async function lockGroupEvidence(
  tx: typeof db,
  scope: RemediationScope,
  itemIds: string[],
): Promise<void> {
  // 1. The identities themselves.
  await tx
    .select({ id: inventoryItems.id })
    .from(inventoryItems)
    .where(and(inArray(inventoryItems.id, itemIds), eq(inventoryItems.companyId, scope.companyId)))
    .orderBy(inventoryItems.id)
    .for('update');

  // 2. Count history — the valuation and the per-line fingerprint come from
  //    here, and this is the evidence the repair actually moves.
  await tx
    .select({ id: inventoryCountLines.id })
    .from(inventoryCountLines)
    .where(inArray(inventoryCountLines.inventoryItemId, itemIds))
    .orderBy(inventoryCountLines.id)
    .for('update');

  // 3. Merge-sensitive configuration: conversion factors, par targets, primary
  //    flags and active flags are all compared value-by-value before merging.
  await tx
    .select({ id: inventoryItemUnits.id })
    .from(inventoryItemUnits)
    .where(inArray(inventoryItemUnits.inventoryItemId, itemIds))
    .orderBy(inventoryItemUnits.id)
    .for('update');

  await tx
    .select({ id: storeInventoryItems.id })
    .from(storeInventoryItems)
    .where(inArray(storeInventoryItems.inventoryItemId, itemIds))
    .orderBy(storeInventoryItems.id)
    .for('update');

  await tx
    .select({ id: inventoryItemLocationAssignments.id })
    .from(inventoryItemLocationAssignments)
    .where(inArray(inventoryItemLocationAssignments.inventoryItemId, itemIds))
    .orderBy(inventoryItemLocationAssignments.id)
    .for('update');

  await tx
    .select({ id: inventoryItemLocations.id })
    .from(inventoryItemLocations)
    .where(inArray(inventoryItemLocations.inventoryItemId, itemIds))
    .orderBy(inventoryItemLocations.id)
    .for('update');

  // 4. Identity mappings — the authoritative binding canonical selection and
  //    the scope check both read.
  await tx
    .select({ id: inventoryItemExternalMappings.id })
    .from(inventoryItemExternalMappings)
    .where(inArray(inventoryItemExternalMappings.inventoryItemId, itemIds))
    .orderBy(inventoryItemExternalMappings.id)
    .for('update');

  // 5. Source import rows — provenance, compatibility evidence and the
  //    earliest-import signal that decides the canonical.
  await tx
    .select({ id: inventoryImportRows.id })
    .from(inventoryImportRows)
    .where(inArray(inventoryImportRows.resolvedInventoryItemId, itemIds))
    .orderBy(inventoryImportRows.id)
    .for('update');
}


/**
 * Recomputes `store_inventory_items.on_hand_qty` for the canonical item from the
 * count history that now belongs to it.
 *
 * This is required, not cosmetic. Repointing moves a duplicate's count lines
 * onto the canonical item, which changes what the authoritative history says the
 * canonical's on-hand should be — but the canonical's store row still holds the
 * value computed back when the count was applied to the *pre-merge* identities.
 * Leaving it stale would understate on-hand for a store whose counts lived on a
 * duplicate, which feeds directly into ordering and variance.
 *
 * The formula mirrors the count-apply handler exactly: applying a session
 * OVERWRITES on-hand with the sum of that session's line quantities for the
 * item, rolled up across storage locations. It is not a cumulative sum over all
 * sessions, so this uses the latest applied session per store and sums its lines
 * — the same value the apply handler would have produced had the count been
 * recorded against the canonical item in the first place.
 *
 * Quantities themselves are never recalculated or converted here; only the
 * derived per-store rollup is refreshed from lines this transaction moved.
 */
async function recomputeStoreOnHand(
  tx: typeof db,
  scope: RemediationScope,
  canonicalItemId: string,
): Promise<void> {
  const storeRows = (await tx
    .select({ id: storeInventoryItems.id, storeId: storeInventoryItems.storeId })
    .from(storeInventoryItems)
    .where(
      and(
        eq(storeInventoryItems.inventoryItemId, canonicalItemId),
        eq(storeInventoryItems.companyId, scope.companyId),
      ),
    )) as Array<{ id: string; storeId: string }>;

  for (const storeRow of storeRows) {
    // The latest APPLIED session for this store is the one whose totals the
    // live on-hand value represents. Unapplied sessions never touched on-hand,
    // so they must not influence it here either.
    const [latest] = (await tx
      .select({ id: inventoryCounts.id })
      .from(inventoryCounts)
      .where(
        and(
          eq(inventoryCounts.companyId, scope.companyId),
          eq(inventoryCounts.storeId, storeRow.storeId),
          eq(inventoryCounts.applied, 1),
        ),
      )
      .orderBy(desc(inventoryCounts.countDate), desc(inventoryCounts.appliedAt))
      .limit(1)) as Array<{ id: string }>;

    // No applied count for this store means there is no authoritative history to
    // derive from. Writing 0 would invent a fact, so the existing value stands.
    if (!latest) continue;

    const [totals] = (await tx
      .select({ total: sql<number | string | null>`sum(${inventoryCountLines.qty})` })
      .from(inventoryCountLines)
      .where(
        and(
          eq(inventoryCountLines.inventoryCountId, latest.id),
          eq(inventoryCountLines.inventoryItemId, canonicalItemId),
        ),
      )) as Array<{ total: number | string | null }>;

    // The canonical may legitimately be absent from the latest session (it was
    // not counted). The apply handler only writes items present in the session,
    // so mirroring that means leaving the row untouched.
    if (totals?.total === null || totals?.total === undefined) continue;

    await tx
      .update(storeInventoryItems)
      .set({ onHandQty: Number(totals.total), updatedAt: new Date() })
      .where(eq(storeInventoryItems.id, storeRow.id));
  }
}

async function recomputeGroupValuation(
  runner: typeof db,
  companyId: string,
  itemIds: string[],
): Promise<number> {
  let total = 0;
  for (const itemId of itemIds) {
    const evidence = await countEvidence(runner, companyId, itemId);
    total += evidence.valuation;
  }
  return round2(total);
}

async function writeAudit(
  runner: typeof db,
  input: {
    manifest: ApplyManifest;
    approval: ManifestGroupApproval;
    group: RemediationGroup;
    operatorId: string;
    result: 'applied' | 'already_remediated' | 'stopped';
    failureReason: string | null;
    referencesMoved: ReferenceCounts;
    /** Store rows merged under the approved primary-location-only rule. */
    primaryLocationMerges?: PrimaryLocationMergeRecord[];
    valuationBefore: number;
    valuationAfter: number;
  },
): Promise<string> {
  const { manifest, approval, group } = input;
  const [row] = (await runner
    .insert(inventoryItemRemediationAudit)
    .values({
      companyId: manifest.scope.companyId,
      storeId: manifest.scope.storeId,
      sourceSystem: manifest.scope.sourceSystem,
      sourcePropertyId: manifest.scope.sourcePropertyId,
      sourceExternalId: approval.sourceExternalId,
      manifestId: manifest.manifestId,
      reportHash: manifest.reportHash,
      reportVersion: manifest.reportVersion,
      canonicalItemId: approval.canonicalItemId,
      canonicalSelectionReason: group.canonicalSelectionReason ?? 'n/a',
      supersededItemIds: approval.supersededItemIds,
      classification: group.classification,
      result: input.result,
      failureReason: input.failureReason,
      referencesMoved: {
        moved: input.referencesMoved,
        unchanged: {
          historicalInvoiceLines: group.referencesToRepoint.historicalInvoiceLines,
          poRoutingAudit: group.referencesToRepoint.poRoutingAudit,
        },
        countLocations: group.affectedCountLocations,
        countSessions: group.affectedCountSessions,
        // Evidence for the approved primary-location-only merge rule: the
        // discarded value is recorded here, in this repair's own audit row,
        // never by altering historical source evidence.
        ...(input.primaryLocationMerges && input.primaryLocationMerges.length > 0
          ? { primaryLocationMerges: input.primaryLocationMerges }
          : {}),
      },
      evidence: group.evidence,
      valuationBefore: input.valuationBefore,
      valuationAfter: input.valuationAfter,
      valuationDelta: round2(input.valuationAfter - input.valuationBefore),
      operatorId: input.operatorId,
    })
    .returning({ id: inventoryItemRemediationAudit.id })) as Array<{ id: string }>;
  return row.id;
}

